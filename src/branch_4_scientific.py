# Ветвь 4. Научные функции.
# Открывает научный блок калькулятора: модуль, знак, корень,
# экспоненту, логарифм, тригонометрию и константы pi, e.


def abs_value(x):
    """Возвращает модуль числа x: abs_value(-3) = 3."""
    if x < 0:
        return -x
    return x


def sign(x):
    """Возвращает знак числа x: -1, 0 или 1."""
    if x < 0:
        return -1
    if x > 0:
        return 1
    return 0
