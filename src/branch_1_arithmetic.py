# Ветвь 1. Элементарная арифметика.


def add(a, b):
    """Возвращает сумму двух чисел: a + b."""
    return a + b
    
def subtract(a, b):
    """Возвращает разность двух чисел: a - b."""
    return a - b
    
def multiply(a, b):
    """Возвращает произведение двух чисел: a * b."""
    return a * b
